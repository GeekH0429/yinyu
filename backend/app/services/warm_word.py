async def pick_random(db: AsyncSession, scene: str) -> WarmWord:
    """按场景随机取一条暖话。场景内为空 → NotFound。"""
    row = await db.execute(
        select(WarmWord)
        .where(WarmWord.scene == scene)
        .order_by(func.random())
        .limit(1)
    )
    ww = row.scalar_one_or_none()
    if ww is None:
        raise NotFound("该场景暂无暖话")
    return ww


async def seed_warm_words(db: AsyncSession) -> None:
    """启动 seed:表空全量;表非空按 (scene, text) 去重增量插入。幂等。"""
    cnt = await db.scalar(select(func.count()).select_from(WarmWord))
    if not cnt:
        # 首次启动:全量
        objs = [
            WarmWord(scene=scene, text=text)
            for scene, words in _SEED_WORDS.items()
            for text in words
        ]
        db.add_all(objs)
        await db.commit()
        print(f"[bootstrap] seed 暖话语料 {len(objs)} 条")
        return

    # 增量:仅插入新条
    existing = await db.execute(select(WarmWord.scene, WarmWord.text))
    existing_set = {(s, t) for s, t in existing.all()}
    new_objs = [
        WarmWord(scene=scene, text=text)
        for scene, words in _SEED_WORDS.items()
        for text in words
        if (scene, text) not in existing_set
    ]
    if new_objs:
        db.add_all(new_objs)
        await db.commit()
        print(f"[bootstrap] 增量 seed 暖话语料 {len(new_objs)} 条")
