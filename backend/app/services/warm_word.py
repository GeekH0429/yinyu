async def pick_random(db: AsyncSession, scene: str) -> WarmWord:
    """按场景随机取一条暖话。场景内为空 → NotFound。"""
    row = await db.execute(
        select(WarmWord)
        .where(WarmWord.scene == scene)
        .order_by(func.random())
        .limit(1)
    )
    ww = row.scalar_one_or_none()
    if ww is None:
        raise NotFound("该场景暂无暖话")
    return ww


async def seed_warm_words(db: AsyncSession) -> None:
    """首次启动 seed:表空时一次性插入 60 条种子语料。幂等。"""
    cnt = await db.scalar(select(func.count()).select_from(WarmWord))
    if cnt:
        return
    objs: list[WarmWord] = []
    for scene, words in _SEED_WORDS.items():
        for text in words:
            objs.append(WarmWord(scene=scene, text=text))
    db.add_all(objs)
    await db.commit()
    print(f"[bootstrap] 已 seed 暖话语料 {len(objs)} 条")
